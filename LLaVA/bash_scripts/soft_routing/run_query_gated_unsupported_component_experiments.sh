#!/bin/bash

set -euo pipefail

GPU_ID="${GPU_ID:-0}"
DATASET="${DATASET:-coco}"
NUM_SAMPLES="${NUM_SAMPLES:-50}"
SEED="${SEED:-42}"
ADHH_THRESHOLD="${ADHH_THRESHOLD:-0.4}"
SOFT_TEMPERATURE="${SOFT_TEMPERATURE:-0.05}"
QUERY_NORMALIZATION="${QUERY_NORMALIZATION:-l2}"
MIN_LAYER="${MIN_LAYER:-13}"
MAX_LAYER="${MAX_LAYER:-31}"
HALLUCINATED_SOURCE="${HALLUCINATED_SOURCE:-both}"
MAX_PER_LABEL="${MAX_PER_LABEL:-100}"

UNSUPPORTED_COMPONENT_GAMMA="${UNSUPPORTED_COMPONENT_GAMMA:-0.5}"
UNSUPPORTED_COMPONENT_ACTION="${UNSUPPORTED_COMPONENT_ACTION:-suppress_unsupported}"
UNSUPPORTED_COMPONENT_RISK_FEATURE="${UNSUPPORTED_COMPONENT_RISK_FEATURE:-unsupported_norm}"
UNSUPPORTED_COMPONENT_SCORE_NORM="${UNSUPPORTED_COMPONENT_SCORE_NORM:-candidate_minmax}"
UNSUPPORTED_COMPONENT_PHASE="${UNSUPPORTED_COMPONENT_PHASE:-decode}"
UNSUPPORTED_COMPONENT_LAYERS="${UNSUPPORTED_COMPONENT_LAYERS:-}"
UNSUPPORTED_COMPONENT_ALL_HEADS="${UNSUPPORTED_COMPONENT_ALL_HEADS:-1}"
UNSUPPORTED_COMPONENT_QUERY_GATE_TOP_K="${UNSUPPORTED_COMPONENT_QUERY_GATE_TOP_K:-10}"
UNSUPPORTED_COMPONENT_QUERY_GATE_MIN_AUROC="${UNSUPPORTED_COMPONENT_QUERY_GATE_MIN_AUROC:-0.65}"
UNSUPPORTED_COMPONENT_QUERY_GATE_MODE="${UNSUPPORTED_COMPONENT_QUERY_GATE_MODE:-prefill_hard}"
UNSUPPORTED_COMPONENT_QUERY_GATE_AGGREGATION="${UNSUPPORTED_COMPONENT_QUERY_GATE_AGGREGATION:-mean}"
UNSUPPORTED_COMPONENT_QUERY_GATE_TEMPERATURE="${UNSUPPORTED_COMPONENT_QUERY_GATE_TEMPERATURE:-0.05}"
UNSUPPORTED_COMPONENT_QUERY_GATE_DEFAULT="${UNSUPPORTED_COMPONENT_QUERY_GATE_DEFAULT:-0.0}"
UNSUPPORTED_COMPONENT_QUERY_GATE_MIN="${UNSUPPORTED_COMPONENT_QUERY_GATE_MIN:-0.0}"
UNSUPPORTED_COMPONENT_QUERY_GATE_POWER="${UNSUPPORTED_COMPONENT_QUERY_GATE_POWER:-1.0}"

BASE_RESULT_PATH="${BASE_RESULT_PATH:-./results/${DATASET}/soft_routing_smoke_n500_seed${SEED}_tau${ADHH_THRESHOLD}_T${SOFT_TEMPERATURE}}"
QUERY_PROBE_DIR="${QUERY_PROBE_DIR:-${BASE_RESULT_PATH}/query_direction_probe_${QUERY_NORMALIZATION}_l${MIN_LAYER}_${MAX_LAYER}_hall${HALLUCINATED_SOURCE}_max${MAX_PER_LABEL}}"
UNSUPPORTED_COMPONENT_QUERY_GATE_CALIBRATION="${UNSUPPORTED_COMPONENT_QUERY_GATE_CALIBRATION:-${QUERY_PROBE_DIR}/query_direction_calibration.npz}"

gate_tag="qgate_${UNSUPPORTED_COMPONENT_QUERY_GATE_MODE}_top${UNSUPPORTED_COMPONENT_QUERY_GATE_TOP_K}_${UNSUPPORTED_COMPONENT_QUERY_GATE_AGGREGATION}"
layer_tag="${UNSUPPORTED_COMPONENT_LAYERS:-all}"
layer_tag="${layer_tag//,/_}"
layer_tag="${layer_tag//-/_}"
OUTPUT_DIR="${OUTPUT_DIR:-${BASE_RESULT_PATH}/diag_${gate_tag}_${UNSUPPORTED_COMPONENT_RISK_FEATURE}_${UNSUPPORTED_COMPONENT_SCORE_NORM}_${UNSUPPORTED_COMPONENT_PHASE}_l${layer_tag}_g${UNSUPPORTED_COMPONENT_GAMMA}_n${NUM_SAMPLES}}"

if [ ! -f "${UNSUPPORTED_COMPONENT_QUERY_GATE_CALIBRATION}" ]; then
    echo "[error] missing query gate calibration: ${UNSUPPORTED_COMPONENT_QUERY_GATE_CALIBRATION}" >&2
    echo "[hint] run bash_scripts/soft_routing/run_query_direction_probe.sh first" >&2
    exit 1
fi

echo "[info] query gate calibration: ${UNSUPPORTED_COMPONENT_QUERY_GATE_CALIBRATION}"
echo "[info] output dir: ${OUTPUT_DIR}"

GPU_ID="${GPU_ID}" \
DATASET="${DATASET}" \
NUM_SAMPLES="${NUM_SAMPLES}" \
SEED="${SEED}" \
ADHH_THRESHOLD="${ADHH_THRESHOLD}" \
SOFT_TEMPERATURE="${SOFT_TEMPERATURE}" \
BASE_RESULT_PATH="${BASE_RESULT_PATH}" \
OUTPUT_DIR="${OUTPUT_DIR}" \
UNSUPPORTED_COMPONENT_GAMMA="${UNSUPPORTED_COMPONENT_GAMMA}" \
UNSUPPORTED_COMPONENT_ACTION="${UNSUPPORTED_COMPONENT_ACTION}" \
UNSUPPORTED_COMPONENT_RISK_FEATURE="${UNSUPPORTED_COMPONENT_RISK_FEATURE}" \
UNSUPPORTED_COMPONENT_SCORE_NORM="${UNSUPPORTED_COMPONENT_SCORE_NORM}" \
UNSUPPORTED_COMPONENT_PHASE="${UNSUPPORTED_COMPONENT_PHASE}" \
UNSUPPORTED_COMPONENT_LAYERS="${UNSUPPORTED_COMPONENT_LAYERS}" \
UNSUPPORTED_COMPONENT_ALL_HEADS="${UNSUPPORTED_COMPONENT_ALL_HEADS}" \
UNSUPPORTED_COMPONENT_QUERY_GATE_CALIBRATION="${UNSUPPORTED_COMPONENT_QUERY_GATE_CALIBRATION}" \
UNSUPPORTED_COMPONENT_QUERY_GATE_TOP_K="${UNSUPPORTED_COMPONENT_QUERY_GATE_TOP_K}" \
UNSUPPORTED_COMPONENT_QUERY_GATE_MIN_AUROC="${UNSUPPORTED_COMPONENT_QUERY_GATE_MIN_AUROC}" \
UNSUPPORTED_COMPONENT_QUERY_GATE_MODE="${UNSUPPORTED_COMPONENT_QUERY_GATE_MODE}" \
UNSUPPORTED_COMPONENT_QUERY_GATE_AGGREGATION="${UNSUPPORTED_COMPONENT_QUERY_GATE_AGGREGATION}" \
UNSUPPORTED_COMPONENT_QUERY_GATE_TEMPERATURE="${UNSUPPORTED_COMPONENT_QUERY_GATE_TEMPERATURE}" \
UNSUPPORTED_COMPONENT_QUERY_GATE_DEFAULT="${UNSUPPORTED_COMPONENT_QUERY_GATE_DEFAULT}" \
UNSUPPORTED_COMPONENT_QUERY_GATE_MIN="${UNSUPPORTED_COMPONENT_QUERY_GATE_MIN}" \
UNSUPPORTED_COMPONENT_QUERY_GATE_POWER="${UNSUPPORTED_COMPONENT_QUERY_GATE_POWER}" \
bash bash_scripts/soft_routing/run_online_unsupported_component_experiments.sh
