#!/bin/bash

set -euo pipefail

DATASET="${DATASET:-coco}"
NUM_SAMPLES="${NUM_SAMPLES:-500}"
SEED="${SEED:-42}"
ADHH_THRESHOLD="${ADHH_THRESHOLD:-0.4}"
SOFT_TEMPERATURE="${SOFT_TEMPERATURE:-0.05}"
FORCE="${FORCE:-0}"

CROSS_LAYER_TOP_K="${CROSS_LAYER_TOP_K:-10}"
CROSS_LAYER_SCORE_FIELD="${CROSS_LAYER_SCORE_FIELD:-pearson}"
CROSS_LAYER_MIN_SCORE="${CROSS_LAYER_MIN_SCORE:-}"

UNSUPPORTED_COMPONENT_GAMMA="${UNSUPPORTED_COMPONENT_GAMMA:-0.5}"
UNSUPPORTED_COMPONENT_ACTION="${UNSUPPORTED_COMPONENT_ACTION:-suppress_unsupported}"
UNSUPPORTED_COMPONENT_RISK_FEATURE="${UNSUPPORTED_COMPONENT_RISK_FEATURE:-unsupported_norm}"
UNSUPPORTED_COMPONENT_SCORE_NORM="${UNSUPPORTED_COMPONENT_SCORE_NORM:-candidate_minmax}"
UNSUPPORTED_COMPONENT_SCORE_LOW="${UNSUPPORTED_COMPONENT_SCORE_LOW:-0.0}"
UNSUPPORTED_COMPONENT_SCORE_HIGH="${UNSUPPORTED_COMPONENT_SCORE_HIGH:-1.0}"
UNSUPPORTED_COMPONENT_PHASE="${UNSUPPORTED_COMPONENT_PHASE:-decode}"
UNSUPPORTED_COMPONENT_LAYERS="${UNSUPPORTED_COMPONENT_LAYERS:-}"
UNSUPPORTED_COMPONENT_OBJECT_VOCAB_PATH="${UNSUPPORTED_COMPONENT_OBJECT_VOCAB_PATH:-eval_scripts/eval_utils/data/synonyms.txt}"
RECORD_UNSUPPORTED_COMPONENT_DIAGNOSTICS="${RECORD_UNSUPPORTED_COMPONENT_DIAGNOSTICS:-0}"
RECORD_UNSUPPORTED_COMPONENT_CANDIDATES="${RECORD_UNSUPPORTED_COMPONENT_CANDIDATES:-0}"
UNSUPPORTED_COMPONENT_DIAGNOSTICS_MAX_RECORDS="${UNSUPPORTED_COMPONENT_DIAGNOSTICS_MAX_RECORDS:-0}"

BASE_RESULT_PATH="${BASE_RESULT_PATH:-./results/${DATASET}/soft_routing_smoke_n${NUM_SAMPLES}_seed${SEED}_tau${ADHH_THRESHOLD}_T${SOFT_TEMPERATURE}}"
CROSS_LAYER_CORRELATIONS="${CROSS_LAYER_CORRELATIONS:-${BASE_RESULT_PATH}/cross_layer_candidate_log_n10/cross_layer_analysis/cross_layer_head_correlations.csv}"
CROSS_LAYER_POOL_DIR="${CROSS_LAYER_POOL_DIR:-${BASE_RESULT_PATH}/cross_layer_candidate_pools}"
CROSS_LAYER_POOL_PATH="${CROSS_LAYER_POOL_PATH:-${CROSS_LAYER_POOL_DIR}/cross_layer_top${CROSS_LAYER_TOP_K}_${CROSS_LAYER_SCORE_FIELD}.json}"
OUTPUT_DIR="${OUTPUT_DIR:-${BASE_RESULT_PATH}/online_unsupported_cross_layer_top${CROSS_LAYER_TOP_K}_${UNSUPPORTED_COMPONENT_RISK_FEATURE}_g${UNSUPPORTED_COMPONENT_GAMMA}}"

if [ ! -f "${CROSS_LAYER_CORRELATIONS}" ]; then
    echo "[error] missing cross-layer correlations: ${CROSS_LAYER_CORRELATIONS}" >&2
    echo "[hint] run analyze_cross_layer_unsupported_dependencies first, or set CROSS_LAYER_CORRELATIONS" >&2
    exit 1
fi

mkdir -p "${CROSS_LAYER_POOL_DIR}"

echo "[info] cross-layer correlations: ${CROSS_LAYER_CORRELATIONS}"
echo "[info] cross-layer pool: ${CROSS_LAYER_POOL_PATH}"
echo "[info] cross-layer top-k: ${CROSS_LAYER_TOP_K}"
echo "[info] score field: ${CROSS_LAYER_SCORE_FIELD}"
echo "[info] min score: ${CROSS_LAYER_MIN_SCORE:-none}"

pool_args=(
    --correlations-csv "${CROSS_LAYER_CORRELATIONS}"
    --output-path "${CROSS_LAYER_POOL_PATH}"
    --top-k "${CROSS_LAYER_TOP_K}"
    --score-field "${CROSS_LAYER_SCORE_FIELD}"
)
if [ -n "${CROSS_LAYER_MIN_SCORE}" ]; then
    pool_args+=(--min-score "${CROSS_LAYER_MIN_SCORE}")
fi

if [ "${FORCE}" = "1" ] || [ ! -f "${CROSS_LAYER_POOL_PATH}" ]; then
    python -m eval_scripts.soft_routing.build_cross_layer_candidate_pool "${pool_args[@]}"
else
    echo "[skip] cross-layer pool exists: ${CROSS_LAYER_POOL_PATH}"
fi

DATASET="${DATASET}" \
NUM_SAMPLES="${NUM_SAMPLES}" \
SEED="${SEED}" \
ADHH_THRESHOLD="${ADHH_THRESHOLD}" \
SOFT_TEMPERATURE="${SOFT_TEMPERATURE}" \
FORCE="${FORCE}" \
UNSUPPORTED_COMPONENT_HEAD_PATH="${CROSS_LAYER_POOL_PATH}" \
UNSUPPORTED_COMPONENT_HEAD_TOP_K="${CROSS_LAYER_TOP_K}" \
UNSUPPORTED_COMPONENT_RISK_FEATURE="${UNSUPPORTED_COMPONENT_RISK_FEATURE}" \
UNSUPPORTED_COMPONENT_GAMMA="${UNSUPPORTED_COMPONENT_GAMMA}" \
UNSUPPORTED_COMPONENT_ACTION="${UNSUPPORTED_COMPONENT_ACTION}" \
UNSUPPORTED_COMPONENT_SCORE_NORM="${UNSUPPORTED_COMPONENT_SCORE_NORM}" \
UNSUPPORTED_COMPONENT_SCORE_LOW="${UNSUPPORTED_COMPONENT_SCORE_LOW}" \
UNSUPPORTED_COMPONENT_SCORE_HIGH="${UNSUPPORTED_COMPONENT_SCORE_HIGH}" \
UNSUPPORTED_COMPONENT_PHASE="${UNSUPPORTED_COMPONENT_PHASE}" \
UNSUPPORTED_COMPONENT_LAYERS="${UNSUPPORTED_COMPONENT_LAYERS}" \
UNSUPPORTED_COMPONENT_OBJECT_VOCAB_PATH="${UNSUPPORTED_COMPONENT_OBJECT_VOCAB_PATH}" \
RECORD_UNSUPPORTED_COMPONENT_DIAGNOSTICS="${RECORD_UNSUPPORTED_COMPONENT_DIAGNOSTICS}" \
RECORD_UNSUPPORTED_COMPONENT_CANDIDATES="${RECORD_UNSUPPORTED_COMPONENT_CANDIDATES}" \
UNSUPPORTED_COMPONENT_DIAGNOSTICS_MAX_RECORDS="${UNSUPPORTED_COMPONENT_DIAGNOSTICS_MAX_RECORDS}" \
UNSUPPORTED_COMPONENT_ALL_HEADS=0 \
OUTPUT_DIR="${OUTPUT_DIR}" \
bash bash_scripts/soft_routing/run_online_unsupported_component_experiments.sh
